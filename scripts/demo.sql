-- 시연용 조회 SQL — :KEY 를 APPLICANT_KEY 로 바꿔 실행
-- (CREATE_TIME / CREATE_DATE 는 DB 기본값 SYSDATE 로 자동 기록)

-- 1) 당일 적재된 주문 (시연 조건: 참여자 키 + 당일 날짜)
SELECT ORDER_ID, USER_ID, ITEM_ID, NAME, ADDRESS, ITEM_NAME, PRICE, STATUS, CREATE_TIME
  FROM ORDER_TB
 WHERE APPLICANT_KEY = :KEY
   AND CREATE_TIME >= TRUNC(SYSDATE)
 ORDER BY ORDER_ID;

-- 2) 당일 운송 적재 건 + 원 주문 대조
SELECT s.SHIPMENT_ID, s.ORDER_ID, s.ITEM_ID, s.ADDRESS, o.STATUS, s.CREATE_DATE
  FROM SHIPMENT_TB s
  JOIN ORDER_TB o ON o.APPLICANT_KEY = s.APPLICANT_KEY AND o.ORDER_ID = s.ORDER_ID
 WHERE s.APPLICANT_KEY = :KEY
   AND s.CREATE_DATE >= TRUNC(SYSDATE)
 ORDER BY s.SHIPMENT_ID;

-- 3) 상태 요약 (N = 운송 대기, Y = 운송 적재 완료)
SELECT STATUS, COUNT(*) FROM ORDER_TB WHERE APPLICANT_KEY = :KEY GROUP BY STATUS;

-- 4) 정합성 점검 — 둘 다 0 이어야 정상
--    Y 인데 운송 기록 없음 / 운송 기록이 있는데 N
SELECT COUNT(*) AS Y_WITHOUT_SHIPMENT FROM ORDER_TB o
 WHERE o.APPLICANT_KEY = :KEY AND o.STATUS = 'Y'
   AND NOT EXISTS (SELECT 1 FROM SHIPMENT_TB s WHERE s.APPLICANT_KEY = o.APPLICANT_KEY AND s.ORDER_ID = o.ORDER_ID);
SELECT COUNT(*) AS SHIPPED_BUT_N FROM ORDER_TB o
 WHERE o.APPLICANT_KEY = :KEY AND o.STATUS = 'N'
   AND EXISTS (SELECT 1 FROM SHIPMENT_TB s WHERE s.APPLICANT_KEY = o.APPLICANT_KEY AND s.ORDER_ID = o.ORDER_ID);
